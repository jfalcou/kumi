//! These texts ground the terminology of the Glossary, from the textbooks to the original papers, and its notations of
//! products and sums follow them together with the standard mathematical notation for sets and tuples. The terms of the
//! C++ language are defined on the [C++ Vocabulary](@ref kumi_cpp_vocabulary) page, and the terms specific to the
//! library on the [Nomenclature](@ref kumi_nomenclature) page.
